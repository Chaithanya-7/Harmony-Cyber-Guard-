/**
 * Forensic Report Generator
 * Converts call analysis data into a structured, legal-ready evidence document.
 */

import { type AnalysisResult } from './audio/FraudAnalysisPipeline';

export interface ForensicReport {
  reportId: string;
  timestamp: string;
  callerInfo: {
    number: string;
    location: string;
    carrier: string;
    lineType: string;
  };
  threatAssessment: {
    riskLevel: string;
    fraudProbability: number;
    indicators: string[];
    deepfakeScore: number;
  };
  behavioralProfile: {
    strategy: string;
    urgency: number;
    authority: number;
    fearTactic: number;
  };
  transcriptSummary: string;
  legalNotice: string;
}

export const generateForensicReport = (
  phoneNumber: string,
  callerMetadata: any,
  lastResult: any,
  fullTranscript: string
): ForensicReport => {
  const reportId = `CG-${Math.random().toString(36).substring(2, 11).toUpperCase()}`;
  
  return {
    reportId,
    timestamp: new Date().toISOString(),
    callerInfo: {
      number: phoneNumber,
      location: callerMetadata.location || 'Unknown',
      carrier: callerMetadata.carrier || 'Unknown',
      lineType: callerMetadata.carrierType || 'VoIP',
    },
    threatAssessment: {
      riskLevel: lastResult.riskLevel || 'neutral',
      fraudProbability: lastResult.fraudProbability || 0,
      indicators: lastResult.fraudIndicators || [],
      deepfakeScore: lastResult.deepfakeScore || 0,
    },
    behavioralProfile: {
      strategy: lastResult.behavioralProfile?.strategy || 'Unknown',
      urgency: lastResult.behavioralProfile?.urgency || 0,
      authority: lastResult.behavioralProfile?.authority || 0,
      fearTactic: lastResult.behavioralProfile?.fear || 0,
    },
    transcriptSummary: fullTranscript.substring(0, 500) + (fullTranscript.length > 500 ? '...' : ''),
    legalNotice: "This document is generated by Cyber-Guard Forensic Engine. The analysis is based on real-time neural and behavioral patterns and is intended for evidence preservation and preliminary investigation purposes."
  };
};

export const formatReportForPrint = (report: ForensicReport): string => {
  return `
--------------------------------------------------
      CYBER-GUARD FORENSIC EVIDENCE REPORT
--------------------------------------------------
ID: ${report.reportId}
DATE: ${new Date(report.timestamp).toLocaleString()}
--------------------------------------------------

1. CALLER IDENTITY
Number: ${report.callerInfo.number}
Location: ${report.callerInfo.location}
Carrier: ${report.callerInfo.carrier} (${report.callerInfo.lineType})

2. THREAT ASSESSMENT
Risk Level: ${report.threatAssessment.riskLevel.toUpperCase()}
Fraud Probability: ${(report.threatAssessment.fraudProbability * 100).toFixed(1)}%
Deepfake Signature: ${report.threatAssessment.deepfakeScore.toFixed(1)}%
Indicators: ${report.threatAssessment.indicators.join(', ')}

3. BEHAVIORAL PROFILE
Primary Strategy: ${report.behavioralProfile.strategy}
Pressure Level: ${(report.behavioralProfile.urgency * 100).toFixed(1)}%
Authority Level: ${(report.behavioralProfile.authority * 100).toFixed(1)}%

4. EVIDENCE TRANSCRIPT (EXCERPT)
"${report.transcriptSummary}"

--------------------------------------------------
LEGAL NOTICE: ${report.legalNotice}
--------------------------------------------------
  `;
};
